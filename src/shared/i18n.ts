const DICTS: Record<Lang, Record<Key, string>> = { cs, en };

/** Překlad s dosazením {proměnných}. Chybějící klíč vrátí klíč sám - ať je to vidět, ne prázdno. */
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text: string = DICTS[lang]?.[key] ?? DICTS.cs[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

export function makeT(lang: Lang) {
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

/** Jazyk podle systému: čeština a slovenština -> cs, jinak en. */
export function langFromLocale(locale: string): Lang {
  return /^(cs|sk)/i.test(locale) ? 'cs' : 'en';
}
